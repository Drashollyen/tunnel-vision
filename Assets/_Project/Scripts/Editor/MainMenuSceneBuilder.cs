        /// <summary>
        /// Draws the cone-of-vision overlay and a placeholder eyeball (swap in real Nicholas art later).
        /// The output is deterministic, so rebuilding doesn't change the files.
        /// </summary>
        private static void GenerateVisionTextures()
        {
            EnsureFolder(TextureFolder);

            // Dark everywhere except a soft-edged cone pointing up from the center, plus a glow around the eye.
            WriteTexture(ConeTexture, 512, (x, y) =>
            {
                var angle = Mathf.Abs(Mathf.Atan2(x, y) * Mathf.Rad2Deg);
                var distance = Mathf.Sqrt(x * x + y * y);
                var cone = 1f - Mathf.SmoothStep(0f, 1f, Mathf.InverseLerp(ConeHalfAngle - 8f, ConeHalfAngle + 8f, angle));
                cone *= 1f - Mathf.SmoothStep(0f, 1f, Mathf.InverseLerp(0.7f, 1f, distance));
                var glow = 1f - Mathf.SmoothStep(0f, 1f, Mathf.InverseLerp(0.04f, 0.1f, distance));
                var light = Mathf.Max(cone, glow);
                return new Color(Darkness.r, Darkness.g, Darkness.b, Darkness.a * (1f - light));
            });

            // White eyeball, slightly pink and shaded towards the rim, with a dark outline.
            WriteTexture(ScleraTexture, 256, (x, y) =>
            {
                var distance = Mathf.Sqrt(x * x + y * y);
                var shade = Color.Lerp(Color.white, new Color(0.95f, 0.78f, 0.78f, 1f), Mathf.InverseLerp(0.55f, 0.88f, distance));
                var color = distance < 0.88f ? shade : EyeOutline;
                color.a = Coverage(distance, 0.96f);
                return color;
            });

            // Iris with a darker rim, a black pupil and a highlight.
            WriteTexture(IrisTexture, 128, (x, y) =>
            {
                var distance = Mathf.Sqrt(x * x + y * y);
                var color = Color.Lerp(IrisColor, IrisColor * 0.55f, Mathf.InverseLerp(0.6f, 0.94f, distance));
                color = Color.Lerp(color, Color.black, Coverage(distance, 0.45f));
                var highlight = Mathf.Sqrt((x - 0.28f) * (x - 0.28f) + (y - 0.28f) * (y - 0.28f));
                color = Color.Lerp(color, Color.white, Coverage(highlight, 0.14f));
                color.a = Coverage(distance, 0.96f);
                return color;
            });
        }

        /// <summary>Anti-aliased coverage of a circle of the given radius, in the same units as distance.</summary>
        private static float Coverage(float distance, float radius) => Mathf.Clamp01((radius - distance) * 80f);

        /// <summary>
        /// Writes a square PNG. The pixel function gets coordinates from -1 to 1 with (0, 0) at the center and y up.
        /// </summary>
        private static void WriteTexture(string path, int size, System.Func<float, float, Color> pixel)
        {
            var texture = new Texture2D(size, size, TextureFormat.RGBA32, false);
            var pixels = new Color[size * size];
            for (var y = 0; y < size; y++)
            {
                for (var x = 0; x < size; x++)
                {
                    var u = (x + 0.5f) / size * 2f - 1f;
                    var v = (y + 0.5f) / size * 2f - 1f;
                    pixels[y * size + x] = pixel(u, v);
                }
            }

            texture.SetPixels(pixels);
            texture.Apply();
            File.WriteAllBytes(path, texture.EncodeToPNG());
            Object.DestroyImmediate(texture);
            AssetDatabase.ImportAsset(path);
        }

        private static void ConfigureSprite(string path, Vector4 border, TextureWrapMode wrap = TextureWrapMode.Clamp)
        {
            var importer = AssetImporter.GetAtPath(path) as TextureImporter;
            if (importer == null)
            {
                throw new FileNotFoundException($"Sprite not found: {path}");
            }

            var settings = new TextureImporterSettings();
            importer.ReadTextureSettings(settings);
            settings.textureType = TextureImporterType.Sprite;
            settings.spriteMode = (int)SpriteImportMode.Single;
            settings.spriteMeshType = SpriteMeshType.FullRect;
            settings.spriteBorder = border;
            settings.mipmapEnabled = false;
            settings.alphaIsTransparency = true;
            settings.wrapMode = wrap;
            importer.SetTextureSettings(settings);
            importer.SaveAndReimport();
        }

        private static Sprite LoadSprite(string path)
        {
            var sprite = AssetDatabase.LoadAssetAtPath<Sprite>(path);
            if (sprite == null)
            {
                throw new FileNotFoundException($"Sprite not found: {path}");
            }

            return sprite;
        }

        /// <summary>
        /// A static SDF font asset with the printable ASCII characters, so the atlas never changes at runtime.
        /// </summary>
        private static TMP_FontAsset LoadOrCreateFontAsset()
        {
            var asset = AssetDatabase.LoadAssetAtPath<TMP_FontAsset>(FontAssetPath);
            if (asset != null)
            {
                return asset;
            }

            EnsureFolder(FontFolder);
            var font = AssetDatabase.LoadAssetAtPath<Font>(FontFile);
            asset = TMP_FontAsset.CreateFontAsset(font, 72, 8, GlyphRenderMode.SDFAA, 1024, 1024);
            asset.name = Path.GetFileNameWithoutExtension(FontAssetPath);
            AssetDatabase.CreateAsset(asset, FontAssetPath);

            asset.atlasTexture.name = asset.name + " Atlas";
            AssetDatabase.AddObjectToAsset(asset.atlasTexture, asset);
            asset.material.name = asset.name + " Material";
            AssetDatabase.AddObjectToAsset(asset.material, asset);

            var ascii = new char[95];
            for (var i = 0; i < ascii.Length; i++)
            {
                ascii[i] = (char)(32 + i);
            }

            asset.TryAddCharacters(new string(ascii));
            asset.atlasPopulationMode = AtlasPopulationMode.Static;
            EditorUtility.SetDirty(asset);
            AssetDatabase.SaveAssets();
            return asset;
        }

        /// <summary>White text with a dark wood outline and drop shadow, like a painted fairground sign.</summary>
        private static Material LoadOrCreateOutlineMaterial(TMP_FontAsset font)
        {
            var material = AssetDatabase.LoadAssetAtPath<Material>(OutlineMaterialPath);
            if (material != null)
            {
                return material;
            }

            material = new Material(font.material);
            material.SetFloat(ShaderUtilities.ID_FaceDilate, 0.2f);
            material.EnableKeyword(ShaderUtilities.Keyword_Outline);
            material.SetFloat(ShaderUtilities.ID_OutlineWidth, 0.3f);
            material.SetColor(ShaderUtilities.ID_OutlineColor, DarkWood);
            material.EnableKeyword(ShaderUtilities.Keyword_Underlay);
            material.SetColor(ShaderUtilities.ID_UnderlayColor, new Color(0f, 0f, 0f, 0.5f));
            material.SetFloat(ShaderUtilities.ID_UnderlayOffsetY, -0.8f);
            material.SetFloat(ShaderUtilities.ID_UnderlayDilate, 0.3f);
            AssetDatabase.CreateAsset(material, OutlineMaterialPath);
            return material;
        }

        private static void EnsureFolder(string path)
        {
            if (AssetDatabase.IsValidFolder(path))
            {
                return;
            }

            var parent = Path.GetDirectoryName(path).Replace('\\', '/');
            EnsureFolder(parent);
            AssetDatabase.CreateFolder(parent, Path.GetFileName(path));
        }

        private static void SetBarAnchors(RectTransform rect)
        {
            rect.anchorMin = new Vector2(0f, 0.5f);
            rect.anchorMax = new Vector2(1f, 0.5f);
            rect.sizeDelta = new Vector2(0f, 16f / BarScale);
            rect.anchoredPosition = Vector2.zero;
        }

        private static void SetPreferredSize(GameObject go, float width, float height)
        {
            if (!go.TryGetComponent<LayoutElement>(out var element))
            {
                element = go.AddComponent<LayoutElement>();
            }

            element.preferredWidth = width;
            element.preferredHeight = height;
        }

        private static void Stretch(RectTransform rect)
        {
            rect.anchorMin = Vector2.zero;
            rect.anchorMax = Vector2.one;
            rect.offsetMin = rect.offsetMax = Vector2.zero;
        }

        private static void AddClick(Button button, UnityAction action)
        {
            UnityEventTools.AddPersistentListener(button.onClick, action);
        }

        private static void Wire(Object target, string field, Object value)
        {
            var so = new SerializedObject(target);
            so.FindProperty(field).objectReferenceValue = value;
            so.ApplyModifiedPropertiesWithoutUndo();
        }

        private static void Wire(Object target, string field, string value)
        {
            var so = new SerializedObject(target);
            so.FindProperty(field).stringValue = value;
            so.ApplyModifiedPropertiesWithoutUndo();
        }

        /// <summary>Creates menu text in the shared font and sign-style material.</summary>
        private readonly struct TextStyle
        {
            private readonly TMP_FontAsset _font;
            private readonly Material _material;

            public TextStyle(TMP_FontAsset font, Material material)
            {
                _font = font;
                _material = material;
            }

            public TextMeshProUGUI Create(string name, Transform parent, string text, float size)
            {
                var go = new GameObject(name, typeof(RectTransform), typeof(TextMeshProUGUI));
                go.transform.SetParent(parent, false);
                var tmp = go.GetComponent<TextMeshProUGUI>();
                tmp.font = _font;
                tmp.fontSharedMaterial = _material;
                tmp.text = text;
                tmp.fontSize = size;
                tmp.color = Color.white;
                tmp.alignment = TextAlignmentOptions.Center;
                tmp.textWrappingMode = TextWrappingModes.NoWrap;
                return tmp;
            }
        }
